    function translateKnownPhrases() {
        if (currentLang === 'en') return;

        PHRASE_MAP.forEach(item => {
            const targetText = item.en;
            const translatedText = t(item.key);
            if (!translatedText || translatedText === targetText) return;

            // Find matching elements
            const elements = document.querySelectorAll('a, button, span, h5, h6, label');
            elements.forEach(el => {
                // Don't touch elements with data-i18n as they're already processed
                if (el.hasAttribute('data-i18n')) return;
                // Don't touch script/style/input
                if (['SCRIPT', 'STYLE', 'INPUT', 'TEXTAREA'].includes(el.tagName)) return;
                // Don't translate reference numbers
                if (el.classList.contains('font-monospace')) return;

                // Match direct child text nodes
                for (let node of el.childNodes) {
                    if (node.nodeType === Node.TEXT_NODE) {
                        const trimmed = node.nodeValue.trim();
                        if (trimmed === targetText) {
                            node.nodeValue = node.nodeValue.replace(targetText, translatedText);
                        }
                    }
                }
            });
        });
    }

    // Set new language
    function setLanguage(langCode) {
        if (!LANGUAGES.some(l => l.code === langCode)) {
            langCode = 'en';
        }
        currentLang = langCode;
        localStorage.setItem('civic_lang', langCode);
        applyTranslations();
    }

    // Build language dropdown items dynamically
    function renderLanguageList() {
        const container = document.getElementById('languageListContainer');
        if (!container) return;

        container.innerHTML = '';
        LANGUAGES.forEach(lang => {
            const a = document.createElement('a');
            a.className = 'lang-item' + (lang.code === currentLang ? ' active' : '');
            a.setAttribute('data-lang', lang.code);
            a.href = '#';

            a.innerHTML = `
                <div class="d-flex align-items-center gap-2">
                    <span class="fw-semibold">${lang.native}</span>
                    <span class="lang-en-name">(${lang.name})</span>
                </div>
                <i class="fas fa-check lang-check text-warning"></i>
            `;

            a.addEventListener('click', function (e) {
                e.preventDefault();
                setLanguage(lang.code);
            });

            container.appendChild(a);
        });
    }

    // Search filter for language dropdown
    function setupLanguageSearch() {
        const searchInput = document.getElementById('langSearchInput');
        if (!searchInput) return;

        searchInput.addEventListener('input', function () {
            const query = this.value.trim().toLowerCase();
            document.querySelectorAll('#languageListContainer .lang-item').forEach(item => {
                const text = item.textContent.toLowerCase();
                const code = item.getAttribute('data-lang').toLowerCase();
                if (text.includes(query) || code.includes(query)) {
                    item.style.setProperty('display', 'flex', 'important');
                } else {
                    item.style.setProperty('display', 'none', 'important');
                }
            });
        });
    }

