    // Current State
    let currentLang = localStorage.getItem('civic_lang') || 'en';

    // Helper: translate a key
    function t(key) {
        if (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) {
            return TRANSLATIONS[currentLang][key];
        }
        if (TRANSLATIONS.en && TRANSLATIONS.en[key]) {
            return TRANSLATIONS.en[key];
        }
        return key;
    }

    // Apply translations across DOM
    function applyTranslations() {
        const langMeta = LANGUAGES.find(l => l.code === currentLang) || LANGUAGES[0];

        // 1. Set HTML direction & lang attribute
        document.documentElement.setAttribute('lang', currentLang);
        document.documentElement.setAttribute('dir', langMeta.dir);
        if (langMeta.dir === 'rtl') {
            document.body.classList.add('rtl-mode');
        } else {
            document.body.classList.remove('rtl-mode');
        }

        // 2. Update navbar language trigger button
        const labelEl = document.getElementById('currentLangLabel');
        if (labelEl) {
            labelEl.textContent = langMeta.native;
        }

        // 3. Mark active item in dropdown
        document.querySelectorAll('.lang-item').forEach(item => {
            if (item.getAttribute('data-lang') === currentLang) {
                item.classList.add('active');
            } else {
                item.classList.remove('active');
            }
        });

        // 4. Translate elements with data-i18n
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translation = t(key);
            if (translation) {
                // Check if element has child icons that should be preserved
                const icon = el.querySelector('i.fas, i.far, i.fab, i.bi');
                if (icon) {
                    const iconClone = icon.cloneNode(true);
                    el.textContent = ' ';
                    el.prepend(iconClone);
                    el.appendChild(document.createTextNode(' ' + translation));
                } else {
                    el.textContent = translation;
                }
            }
        });

        // 5. Translate placeholders
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            const translation = t(key);
            if (translation) {
                el.setAttribute('placeholder', translation);
            }
        });

        // 6. Translate titles
        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            const key = el.getAttribute('data-i18n-title');
            const translation = t(key);
            if (translation) {
                el.setAttribute('title', translation);
            }
        });

        // 7. Auto-phrase translator for standard non-annotated text elements
        translateKnownPhrases();

        // 8. Dispatch event for other scripts (maps, charts, etc.)
        window.dispatchEvent(new CustomEvent('civicLanguageChanged', { detail: { lang: currentLang, meta: langMeta } }));
    }

